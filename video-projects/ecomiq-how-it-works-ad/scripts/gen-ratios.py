#!/usr/bin/env python3
"""
gen-ratios.py — emit compositions/square.html (1:1) and compositions/meta45.html
(4:5) from index.html (9:16).

index.html is the single source of truth for the edit: timeline, beat anchors,
markup and animation are identical across all three ratios. Only the geometry
block between the @@GEO@@ / @@ENDGEO@@ markers differs, plus the composition id
and the montage bed filename.

Run from the PROJECT folder after editing index.html:

    python3 scripts/gen-ratios.py && npx hyperframes lint

Track indices are offset per variant (0-20 / 30-50 / 60-80) because
`hyperframes lint` merges sibling root compositions into one graph and would
otherwise report bogus duplicate_audio_track overlaps. Track indices are
per-composition, so the offset costs nothing.
"""
