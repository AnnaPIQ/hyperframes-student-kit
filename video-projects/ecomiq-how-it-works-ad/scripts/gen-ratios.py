def build(src: str, v: dict) -> str:
    t = src

    # --- geometry block (the only per-ratio difference) ---
    geo_re = re.compile(r"(/\* @@GEO@@).*?(/\* @@ENDGEO@@ \*/)", re.S)
    if not geo_re.search(t):
        sys.exit("index.html is missing the @@GEO@@ / @@ENDGEO@@ markers")
    block = (
        f"/* @@GEO@@ {v['note']} — generated by scripts/gen-ratios.py from\n"
        f"         index.html. Do NOT edit this file directly: edit index.html\n"
        f"         and the geometry table in scripts/gen-ratios.py, then re-run it. */\n"
        f"      html, body {{ width: {v['W']}px; height: {v['H']}px; }}\n"
        f"      :root {{\n{v['geo']}\n      }}\n"
        f"      /* @@ENDGEO@@ */"
    )
    t = geo_re.sub(lambda _: block, t)

    # --- identity + canvas ---
    t = t.replace("ecomiq-how-it-works-ad — 9:16", f"ecomiq-how-it-works-ad — {v['label']}")
    t = t.replace('data-composition-id="ecomiq-how-it-works-ad"',
                  f'data-composition-id="{v["cid"]}"')
    t = t.replace('window.__timelines["ecomiq-how-it-works-ad"]',
                  f'window.__timelines["{v["cid"]}"]')
    t = t.replace('content="width=1080, height=1920"',
                  f'content="width={v["W"]}, height={v["H"]}"')
    t = t.replace('data-width="1080"\n      data-height="1920"',
                  f'data-width="{v["W"]}"\n      data-height="{v["H"]}"')

    # --- picture bed for this ratio ---
    t = t.replace("montage-916.mp4", v["bed"])

    # --- track offset (see module docstring) ---
    t = re.sub(r'data-track-index="(\d+)"',
               lambda m: f'data-track-index="{int(m.group(1)) + v["tbase"]}"', t)

    # Asset paths stay ROOT-relative: compositions are served with the project
    # root as their base URL, even when rendered via -c compositions/<f>.html.
    # `../assets/...` lints as invalid_parent_traversal_in_asset_path.
    assert "../assets/" not in t
    return t


def main() -> None:
    src = SRC.read_text()
    for rel, v in VARIANTS.items():
        out = HERE / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(build(src, v))
        print(f"wrote {rel}  ({v['label']} {v['W']}x{v['H']}, tracks "
              f"{v['tbase']}-{v['tbase'] + 20}, bed {v['bed']})")


if __name__ == "__main__":
    main()
